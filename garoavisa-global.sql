CREATE OR REPLACE PACKAGE pkg_locais AS
   FUNCTION fn_total_alertas_ativos (p_id_local IN NUMBER)
      RETURN NUMBER;

   PROCEDURE prc_criar_local_principal (
      p_id_usuario  IN NUMBER,
      p_id_endereco IN NUMBER,
      p_apelido     IN VARCHAR2);
END pkg_locais;
/

CREATE OR REPLACE PACKAGE BODY pkg_locais AS

   FUNCTION fn_total_alertas_ativos (p_id_local IN NUMBER)
      RETURN NUMBER
   IS
      v_total NUMBER;
   BEGIN
      SELECT COUNT(*) INTO v_total
        FROM T_GA_ALERTA
       WHERE fk_id_local = p_id_local
         AND status = 'ATIVO';

      RETURN v_total;
   END fn_total_alertas_ativos;

   PROCEDURE prc_criar_local_principal (
      p_id_usuario  IN NUMBER,
      p_id_endereco IN NUMBER,
      p_apelido     IN VARCHAR2)
   IS
      v_total        NUMBER;
      v_user_existe  NUMBER;
   BEGIN
      SELECT id_usuario INTO v_user_existe
        FROM T_GA_USUARIO
       WHERE id_usuario = p_id_usuario;

      SELECT COUNT(*) INTO v_total
        FROM T_GA_LOCAL
       WHERE fk_id_usuario = p_id_usuario
         AND local_principal = 'S';

      IF v_total > 0 THEN
         DBMS_OUTPUT.PUT_LINE('Bloqueado: o usuario ' || p_id_usuario || ' ja possui um local principal.');
      ELSE
         INSERT INTO T_GA_LOCAL (apelido, local_principal, fk_id_usuario, fk_id_endereco)
         VALUES (p_apelido, 'S', p_id_usuario, p_id_endereco);

         COMMIT;
         DBMS_OUTPUT.PUT_LINE('Local principal "' || p_apelido || '" criado para o usuario ' || p_id_usuario || '.');
      END IF;
   EXCEPTION
      WHEN NO_DATA_FOUND THEN
         DBMS_OUTPUT.PUT_LINE('Erro: Usuario ID ' || p_id_usuario || ' nao encontrado.');
      WHEN OTHERS THEN
         DBMS_OUTPUT.PUT_LINE('Erro ao cadastrar local principal: ' || SQLERRM);
   END prc_criar_local_principal;

END pkg_locais;
