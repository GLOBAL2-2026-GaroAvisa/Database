--trigger 1: histórico de auditoria de usuario
CREATE OR REPLACE TRIGGER trg_auditoria_usuario
AFTER UPDATE OF senha, resumo_diario_horario
ON T_GA_USUARIO
FOR EACH ROW
BEGIN
   IF :OLD.senha <> :NEW.senha THEN
      INSERT INTO T_GA_AUDITORIA
         (tipo_operacao, tipo_alteracao, valor_antigo, valor_novo, fk_id_usuario)
      VALUES
         ('UPDATE', 'SENHA', 'senha anterior (oculta)', 'nova senha (oculta)', :OLD.id_usuario);
   END IF;

   IF :OLD.resumo_diario_horario <> :NEW.resumo_diario_horario THEN
      INSERT INTO T_GA_AUDITORIA
         (tipo_operacao, tipo_alteracao, valor_antigo, valor_novo, fk_id_usuario)
      VALUES
         ('UPDATE', 'HORARIO_RESUMO', :OLD.resumo_diario_horario, :NEW.resumo_diario_horario, :OLD.id_usuario);
   END IF;
END;
/

--trigger 2: histórico de auditoria de alerta
CREATE OR REPLACE TRIGGER trg_auditoria_alerta
AFTER INSERT OR UPDATE OF status
ON T_GA_ALERTA
FOR EACH ROW
DECLARE
   v_id_usuario NUMBER;
BEGIN
   SELECT fk_id_usuario INTO v_id_usuario
     FROM T_GA_LOCAL
    WHERE id_local = :NEW.fk_id_local;

   IF :OLD.status IS NULL THEN   
      INSERT INTO T_GA_AUDITORIA
         (tipo_operacao, tipo_alteracao, valor_antigo, valor_novo, fk_id_usuario)
      VALUES
         ('INSERT', 'NOVO_ALERTA', NULL,
          :NEW.tipo_alerta || ' - ' || :NEW.gravidade || ' - ' || :NEW.status,
          v_id_usuario);
   ELSIF :OLD.status <> :NEW.status THEN
      INSERT INTO T_GA_AUDITORIA
         (tipo_operacao, tipo_alteracao, valor_antigo, valor_novo, fk_id_usuario)
      VALUES
         ('UPDATE', 'STATUS_ALERTA', :OLD.status, :NEW.status, v_id_usuario);
   END IF;
EXCEPTION
   WHEN NO_DATA_FOUND THEN
      DBMS_OUTPUT.PUT_LINE('Local nao encontrado para auditoria do alerta.');
END;
/

