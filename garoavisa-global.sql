--bloco 1 - simulação de alerta=================================================
SET SERVEROUTPUT ON
SET VERIFY OFF

DECLARE
   CURSOR c_alertas IS
      SELECT a.titulo, a.gravidade, l.apelido, u.nm_usuario
        FROM T_GA_ALERTA a
        JOIN T_GA_LOCAL   l ON l.id_local   = a.fk_id_local
        JOIN T_GA_USUARIO u ON u.id_usuario = l.fk_id_usuario
       WHERE a.status = 'ATIVO'
       ORDER BY a.dt_alerta DESC;

   v_alerta     c_alertas%ROWTYPE;
   v_orientacao VARCHAR2(60);
BEGIN
   OPEN c_alertas;
   LOOP
      FETCH c_alertas INTO v_alerta;
      EXIT WHEN c_alertas%NOTFOUND;

      IF v_alerta.gravidade = 'ALTA' THEN
         v_orientacao := 'Avalie mudar o horario ou o trajeto.';
      ELSIF v_alerta.gravidade = 'MEDIA' THEN
         v_orientacao := 'Fique atento antes de sair.';
      ELSE
         v_orientacao := 'Apenas informativo.';
      END IF;

      DBMS_OUTPUT.PUT_LINE('[' || v_alerta.gravidade || '] ' || v_alerta.titulo
         || ' - ' || v_alerta.nm_usuario || ' (' || v_alerta.apelido || ')');
      DBMS_OUTPUT.PUT_LINE('   ' || v_orientacao);
   END LOOP;

   DBMS_OUTPUT.PUT_LINE('Total de alertas ativos: ' || c_alertas%ROWCOUNT);
   CLOSE c_alertas;
END;
/

--bloco 2 - simulação gestor====================================================
DECLARE
   CURSOR c_bairros IS
      SELECT e.bairro, COUNT(*) AS total
        FROM T_GA_ALERTA a
        JOIN T_GA_LOCAL    l ON l.id_local    = a.fk_id_local
        JOIN T_GA_ENDERECO e ON e.id_endereco = l.fk_id_endereco
       GROUP BY e.bairro
       ORDER BY total DESC, e.bairro;

   v_nivel VARCHAR2(20);
BEGIN
   FOR r IN c_bairros LOOP
      IF r.total >= 3 THEN
         v_nivel := 'Atencao';
      ELSE
         v_nivel := 'Normal';
      END IF;

      DBMS_OUTPUT.PUT_LINE(r.bairro || ': ' || r.total || ' alerta(s) - ' || v_nivel);
   END LOOP;
END;
/

