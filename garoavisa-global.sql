--criação de tabelas==========================================================--
CREATE TABLE T_GA_USUARIO (
    id_usuario             NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY,
    nm_usuario             VARCHAR2(100) NOT NULL,
    email                  VARCHAR2(100) NOT NULL,
    senha                  VARCHAR2(255) NOT NULL,
    tipo_usuario           VARCHAR2(10)  DEFAULT 'USUARIO' NOT NULL,
    resumo_diario_ativo    CHAR(1)       DEFAULT 'S' NOT NULL,
    resumo_diario_horario  VARCHAR2(5)   DEFAULT '07:00' NOT NULL,
    alertas_do_dia         CHAR(1)       DEFAULT 'S' NOT NULL,
    previsao_mudou         CHAR(1)       DEFAULT 'S' NOT NULL,
    compromissos           CHAR(1)       DEFAULT 'S' NOT NULL,
    silencio_noturno       CHAR(1)       DEFAULT 'S' NOT NULL,
    CONSTRAINT Usuario_PK              PRIMARY KEY (id_usuario),
    CONSTRAINT Usuario_Email_UK        UNIQUE (email),
    CONSTRAINT Usuario_Tipo_CK         CHECK (tipo_usuario IN ('USUARIO', 'ADMIN')),
    CONSTRAINT Usuario_Resumo_CK       CHECK (resumo_diario_ativo IN ('S', 'N')),
    CONSTRAINT Usuario_Alertas_CK      CHECK (alertas_do_dia IN ('S', 'N')),
    CONSTRAINT Usuario_Prev_CK         CHECK (previsao_mudou IN ('S', 'N')),
    CONSTRAINT Usuario_Compromissos_CK CHECK (compromissos IN ('S', 'N')),
    CONSTRAINT Usuario_Silenc_CK       CHECK (silencio_noturno IN ('S', 'N')),
    CONSTRAINT Usuario_Horario_CK      CHECK (resumo_diario_horario LIKE '__:__')
);

CREATE TABLE T_GA_ENDERECO (
    id_endereco  NUMBER(10)   GENERATED BY DEFAULT AS IDENTITY,
    pais         VARCHAR2(50) NOT NULL,
    estado       VARCHAR2(50) NOT NULL,
    cidade       VARCHAR2(60) NOT NULL,
    bairro       VARCHAR2(60) NOT NULL,
    latitude     NUMBER(9,6)  NOT NULL,
    longitude    NUMBER(9,6)  NOT NULL,
    fuso         VARCHAR2(50) NOT NULL,
    CONSTRAINT Endereco_PK             PRIMARY KEY (id_endereco),
    CONSTRAINT Endereco_Coordenadas_UK UNIQUE (latitude, longitude)
);

CREATE TABLE T_GA_LOCAL (
    id_local         NUMBER(10)   GENERATED BY DEFAULT AS IDENTITY,
    apelido          VARCHAR2(50) NOT NULL,
    local_principal  CHAR(1)      DEFAULT 'N' NOT NULL,
    receber_alertas  CHAR(1)      DEFAULT 'S' NOT NULL,
    fk_id_usuario    NUMBER(10)   NOT NULL,
    fk_id_endereco   NUMBER(10)   NOT NULL,
    CONSTRAINT Local_PK                 PRIMARY KEY (id_local),
    CONSTRAINT Local_Usuario_FK         FOREIGN KEY (fk_id_usuario)
        REFERENCES T_GA_USUARIO (id_usuario) ON DELETE CASCADE,
    CONSTRAINT Local_Endereco_FK        FOREIGN KEY (fk_id_endereco)
        REFERENCES T_GA_ENDERECO (id_endereco),
    CONSTRAINT Local_Usuario_Apelido_UK UNIQUE (fk_id_usuario, apelido),
    CONSTRAINT Local_Principal_CK       CHECK (local_principal IN ('S', 'N')),
    CONSTRAINT Local_Receber_CK         CHECK (receber_alertas IN ('S', 'N'))
);

CREATE TABLE T_GA_COMPROMISSO (
    id_compromisso  NUMBER(10)   GENERATED BY DEFAULT AS IDENTITY,
    nm_compromisso  VARCHAR2(80) NOT NULL,
    dt_compromisso  DATE         NOT NULL,
    hr_compromisso  VARCHAR2(5)  NOT NULL,
    fk_id_local     NUMBER(10)   NOT NULL,
    CONSTRAINT Compromisso_PK         PRIMARY KEY (id_compromisso),
    CONSTRAINT Compromisso_Local_FK   FOREIGN KEY (fk_id_local)
        REFERENCES T_GA_LOCAL (id_local) ON DELETE CASCADE,
    CONSTRAINT Compromisso_Horario_CK CHECK (hr_compromisso LIKE '__:__')
);

CREATE TABLE T_GA_ALERTA (
    id_alerta    NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY,
    dt_alerta    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    tipo_alerta  VARCHAR2(30)  NOT NULL,
    titulo       VARCHAR2(100) NOT NULL,
    descricao    VARCHAR2(300) NOT NULL,
    gravidade    VARCHAR2(10)  NOT NULL,
    status       VARCHAR2(10)  DEFAULT 'ATIVO' NOT NULL,
    fk_id_local  NUMBER(10)    NOT NULL,
    CONSTRAINT Alerta_PK           PRIMARY KEY (id_alerta),
    CONSTRAINT Alerta_Local_FK     FOREIGN KEY (fk_id_local)
        REFERENCES T_GA_LOCAL (id_local) ON DELETE CASCADE,
    CONSTRAINT Alerta_Gravidade_CK CHECK (gravidade IN ('BAIXA', 'MEDIA', 'ALTA')),
    CONSTRAINT Alerta_Status_CK    CHECK (status IN ('ATIVO', 'ENCERRADO')),
    CONSTRAINT Alerta_Tipo_CK      CHECK (tipo_alerta IN ('CHUVA', 'CALOR', 'FRIO', 'UV', 'VENTO',
                                                          'UMIDADE', 'AMPLITUDE', 'SECA', 'MUDANCA_PREVISAO'))
);

CREATE TABLE T_GA_AUDITORIA (
    id_audit             NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY,
    tipo_operacao        VARCHAR2(10)  NOT NULL,
    tipo_alteracao       VARCHAR2(50)  NOT NULL,
    data_hora_alteracao  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    valor_antigo         VARCHAR2(1000),
    valor_novo           VARCHAR2(1000),
    fk_id_usuario        NUMBER(10)    NOT NULL,
    CONSTRAINT Auditoria_PK         PRIMARY KEY (id_audit),
    CONSTRAINT Auditoria_Usuario_FK FOREIGN KEY (fk_id_usuario)
        REFERENCES T_GA_USUARIO (id_usuario) ON DELETE CASCADE,
    CONSTRAINT Auditoria_Operacao_CK CHECK (tipo_operacao IN ('INSERT', 'UPDATE', 'DELETE'))
);

