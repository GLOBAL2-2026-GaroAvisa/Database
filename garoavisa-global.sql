--pacote 1: alertas
CREATE OR REPLACE PACKAGE pkg_alertas AS
   FUNCTION fn_nivel_risco (p_tipo IN VARCHAR2, p_valor IN NUMBER)
      RETURN VARCHAR2;

   FUNCTION fn_previsao_mudou (p_temp_antiga IN NUMBER, p_temp_nova IN NUMBER)
      RETURN CHAR;

   PROCEDURE prc_gerar_alerta (
      p_id_local IN NUMBER,
      p_tipo     IN VARCHAR2,
      p_valor    IN NUMBER);
END pkg_alertas;
/

CREATE OR REPLACE PACKAGE BODY pkg_alertas AS

   FUNCTION fn_nivel_risco (p_tipo IN VARCHAR2, p_valor IN NUMBER)
      RETURN VARCHAR2
   IS
      v_lim_alta  NUMBER;
      v_lim_media NUMBER;
   BEGIN
      CASE UPPER(p_tipo)
         WHEN 'CHUVA' THEN v_lim_alta := 10; v_lim_media := 5;
         WHEN 'CALOR' THEN v_lim_alta := 35; v_lim_media := 30;
         WHEN 'UV'    THEN v_lim_alta := 11; v_lim_media := 8;
         WHEN 'VENTO' THEN v_lim_alta := 75; v_lim_media := 50;
         ELSE RETURN 'INVALIDO';
      END CASE;

      IF p_valor >= v_lim_alta THEN
         RETURN 'ALTA';
      ELSIF p_valor >= v_lim_media THEN
         RETURN 'MEDIA';
      ELSE
         RETURN 'BAIXA';
      END IF;
   END fn_nivel_risco;

   FUNCTION fn_previsao_mudou (p_temp_antiga IN NUMBER, p_temp_nova IN NUMBER)
      RETURN CHAR
   IS
      v_diferenca NUMBER(5,2);
      v_mudou     CHAR(1);
   BEGIN
      v_diferenca := ABS(p_temp_nova - p_temp_antiga);

      IF v_diferenca >= 4 THEN
         v_mudou := 'S';
      ELSE
         v_mudou := 'N';
      END IF;

      RETURN v_mudou;
   END fn_previsao_mudou;

   PROCEDURE prc_gerar_alerta (
      p_id_local IN NUMBER,
      p_tipo     IN VARCHAR2,
      p_valor    IN NUMBER)
   IS
      v_gravidade   VARCHAR2(10);
      v_total       NUMBER;
      v_local_existe NUMBER;
   BEGIN
      SELECT id_local INTO v_local_existe
        FROM T_GA_LOCAL
       WHERE id_local = p_id_local;

      v_gravidade := fn_nivel_risco(p_tipo, p_valor);

      IF v_gravidade = 'INVALIDO' THEN
         DBMS_OUTPUT.PUT_LINE('Tipo de alerta invalido: ' || p_tipo);
      ELSIF v_gravidade = 'BAIXA' THEN
         DBMS_OUTPUT.PUT_LINE('Sem risco: ' || p_tipo || ' com valor ' || p_valor || ' nao gera alerta.');
      ELSE
         SELECT COUNT(*) INTO v_total
           FROM T_GA_ALERTA
          WHERE fk_id_local = p_id_local
            AND tipo_alerta = UPPER(p_tipo)
            AND status = 'ATIVO';

         IF v_total > 0 THEN
            DBMS_OUTPUT.PUT_LINE('Ja existe alerta ativo de ' || UPPER(p_tipo) || ' neste local. Nada foi criado.');
         ELSE
            INSERT INTO T_GA_ALERTA (tipo_alerta, titulo, descricao, gravidade, fk_id_local)
            VALUES (UPPER(p_tipo),
                    'Alerta de ' || UPPER(p_tipo) || ' - nivel ' || v_gravidade,
                    'Valor previsto pela Open-Meteo: ' || p_valor,
                    v_gravidade,
                    p_id_local);

            COMMIT;
            DBMS_OUTPUT.PUT_LINE('Alerta de ' || UPPER(p_tipo) || ' (' || v_gravidade || ') criado para o local ' || p_id_local || '.');
         END IF;
      END IF;
   EXCEPTION
      WHEN NO_DATA_FOUND THEN
         DBMS_OUTPUT.PUT_LINE('Erro: Local ID ' || p_id_local || ' nao encontrado.');
      WHEN OTHERS THEN
         DBMS_OUTPUT.PUT_LINE('Erro inesperado ao gerar alerta: ' || SQLERRM);
   END prc_gerar_alerta;

END pkg_alertas;
